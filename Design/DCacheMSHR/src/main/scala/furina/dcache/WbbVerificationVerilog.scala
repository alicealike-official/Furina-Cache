package furina.dcache

import spinal.core._
import java.nio.charset.StandardCharsets
import java.nio.file.{Files, Paths}

/** Generate the WBB DUT and verification constants from one config instance. */
object WbbVerificationVerilog extends App {
    val output = if (args.nonEmpty) args(0) else "../../verif_mshr/generated/wbb"
    val parametersPath = if (args.length > 2) Paths.get(args(2)) else Paths.get(output, "wbb_params_pkg.sv")
    val entries = if (args.length > 1) args(1).toInt else 4
    val cfg = CacheConfig(WBB_ENTRIES = entries)
    Files.createDirectories(Paths.get(output))
    SpinalConfig(targetDirectory = output, withTimescale = false)
        .generateVerilog(new WriteBackBuffer(cfg))

    val parameters = Seq(
        "ADDR_WIDTH" -> cfg.ADDR_WIDTH,
        "DATA_WIDTH" -> cfg.DATA_WIDTH,
        "BLOCK_SIZE" -> cfg.BLOCK_SIZE,
        "LINE_WIDTH" -> cfg.lineWidth,
        "WORDS_PER_BLOCK" -> cfg.wordsPerBlock,
        "WBB_ENTRIES" -> cfg.WBB_ENTRIES,
        "SLOT_WIDTH" -> cfg.wbbIdWidth,
        "BUS_ID_WIDTH" -> cfg.busIdWidth
    )
    val content = "// Generated by WbbVerificationVerilog. Do not edit independently of RTL.\n" +
        "package wbb_params_pkg;\n" +
        parameters.map { case (name, value) =>
            s"    parameter int $name = $value;\n"
        }.mkString + "endpackage\n"
    Option(parametersPath.getParent).foreach(path => Files.createDirectories(path))
    Files.write(parametersPath, content.getBytes(StandardCharsets.UTF_8))
}
