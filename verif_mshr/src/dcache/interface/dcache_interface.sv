    logic cpu_valid;
    logic cpu_ready;
    logic [31:0] cpu_payload_addr;
    logic cpu_payload_wrEn;
    logic [31:0] cpu_payload_wData;
    logic [4:0] cpu_payload_id;
    logic cpuReadResp_valid;
    logic cpuReadResp_ready;
    logic [31:0] cpuReadResp_payload_rData;
    logic [4:0] cpuReadResp_payload_id;
    logic cpuWriteResp_valid;
    logic cpuWriteResp_ready;
    logic [4:0] cpuWriteResp_payload_id;
    logic memReadReq_valid;
    logic memReadReq_ready;
    logic [31:0] memReadReq_payload_addr;
    logic [3:0] memReadReq_payload_id;
    logic memWriteReq_valid;
    logic memWriteReq_ready;
    logic [31:0] memWriteReq_payload_addr;
    logic [511:0] memWriteReq_payload_wData;
    logic [3:0] memWriteReq_payload_id;
    logic memReadResp_valid;
    logic memReadResp_ready;
    logic [511:0] memReadResp_payload_rData;
    logic [3:0] memReadResp_payload_id;
    logic memWriteResp_valid;
    logic memWriteResp_ready;
    logic [3:0] memWriteResp_payload_id;
    clocking mon_cb @(posedge clk);
        default input #1step;
        input rst_n;
        input cpu_valid;
        input cpu_ready;
        input cpu_payload_addr;
        input cpu_payload_wrEn;
        input cpu_payload_wData;
        input cpu_payload_id;
        input cpuReadResp_valid;
        input cpuReadResp_ready;
        input cpuReadResp_payload_rData;
        input cpuReadResp_payload_id;
        input cpuWriteResp_valid;
        input cpuWriteResp_ready;
        input cpuWriteResp_payload_id;
        input memReadReq_valid;
        input memReadReq_ready;
        input memReadReq_payload_addr;
        input memReadReq_payload_id;
        input memWriteReq_valid;
        input memWriteReq_ready;
        input memWriteReq_payload_addr;
        input memWriteReq_payload_wData;
        input memWriteReq_payload_id;
        input memReadResp_valid;
        input memReadResp_ready;
        input memReadResp_payload_rData;
        input memReadResp_payload_id;
        input memWriteResp_valid;
        input memWriteResp_ready;
        input memWriteResp_payload_id;
    endclocking
